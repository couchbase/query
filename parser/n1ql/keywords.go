// lookupKeyword returns the token for s if s is a keyword, ignoring case.
// s is the text matched by the identifier rule, [a-zA-Z_][a-zA-Z0-9_]*, so it
// is ASCII. It is lowercased into buf, which the compiler keeps on the stack
// while it is at most 32 bytes, so the lookup does not allocate.
func lookupKeyword(s string) (int, bool) {
	if len(s) < minKeywordLen || len(s) > maxKeywordLen {
		return 0, false
	}
	buf := make([]byte, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		if 'A' <= c && c <= 'Z' {
			c += 'a' - 'A'
		}
		buf[i] = c
	}
	t, ok := keywords[string(buf)]
	return t, ok
}
