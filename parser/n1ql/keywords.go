package n1ql

import "math"

// Keywords are matched by the identifier rule in n1ql.nex through lookupKeyword,
// rather than by one nex rule per keyword: nex steps every rule's DFA on every
// rune, so one rule per keyword made the lexer several times slower.
//
// To add a keyword, declare it with %token in n1ql.y and add it here.

// Shortest and longest keywords, computed from the keywords map by init.
var minKeywordLen, maxKeywordLen int

func init() {
	minKeywordLen = math.MaxInt
	for k := range keywords {
		if len(k) < minKeywordLen {
			minKeywordLen = len(k)
		}
		if len(k) > maxKeywordLen {
			maxKeywordLen = len(k)
		}
	}
}

